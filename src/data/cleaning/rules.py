@lru_cache(maxsize=None)
def closed_market_ids(path: Path = MARKETS_FILE) -> tuple[int, ...]:
    """Load IDs of markets marked as closed in the market master data."""
    if not path.exists():
        raise FileNotFoundError(f"Market master data not found: {path}")

    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        required_columns = {MARKET_ID_COL, MARKET_OPENING_HOURS_COL}
        missing = sorted(required_columns - set(reader.fieldnames or ()))
        if missing:
            raise ValueError(f"Market master data is missing columns: {missing}")

        ids = {
            int(row[MARKET_ID_COL])
            for row in reader
            if CLOSED_MARKET_LABEL
            in (row[MARKET_OPENING_HOURS_COL] or "").strip().casefold()
        }
    return tuple(sorted(ids))


def allowed_fcm_article_ids_sql() -> str:
    return ", ".join(str(article_id) for article_id in sorted(ALLOWED_FCM_ARTICLE_IDS))


def pseudo_article_ids_sql() -> str:
    return ", ".join(str(article_id) for article_id in sorted(PSEUDO_ARTICLE_IDS))


def excluded_gramm_bon_article_ids_sql() -> str:
    return ", ".join(
        str(article_id) for article_id in sorted(EXCLUDED_GRAMM_BON_ARTICLE_IDS)
    )


def existing_flag_condition(flag_col: str, alias: str | None = None) -> str:
    """Return a null-safe Boolean condition for an existing product flag."""
    col = ident(flag_col)
    if alias:
        col = f"{alias}.{col}"
    return f"COALESCE(TRY_CAST({col} AS BOOLEAN), FALSE)"


def fcm_filter_condition(
    alias: str | None = None,
    *,
    columns: Collection[str] | None = None,
) -> str:
    """Use an existing FCM marker, otherwise identify FCM products by ID."""
    if columns is not None and FCM_COL.casefold() in {
        col.casefold() for col in columns
    }:
        return existing_flag_condition(FCM_COL, alias)
    col = ident(ARTICLE_ID_COL)
    if alias:
        col = f"{alias}.{col}"
    return f"{col} IN ({allowed_fcm_article_ids_sql()})"


def pseudo_filter_condition(
    alias: str | None = None,
    *,
    columns: Collection[str] | None = None,
) -> str:
    """Use an existing pseudo marker, otherwise identify products by ID."""
    if columns is not None and PSEUDO_COL.casefold() in {
        col.casefold() for col in columns
    }:
        return existing_flag_condition(PSEUDO_COL, alias)
    col = ident(ARTICLE_ID_COL)
    if alias:
        col = f"{alias}.{col}"
    return f"{col} IN ({pseudo_article_ids_sql()})"


def fcm_or_pseudo_filter_condition(
    alias: str | None = None,
    *,
    columns: Collection[str] | None = None,
) -> str:
    """Keep known FCM and pseudo products, excluding external products."""
    return (
        f"(({fcm_filter_condition(alias, columns=columns)}) "
        f"OR ({pseudo_filter_condition(alias, columns=columns)}))"
    )


def gramm_bon_filter_condition(alias: str | None = None) -> str:
    """Remove every row belonging to an article with suspicious GRAMM_BON."""
    col = ident(ARTICLE_ID_COL)
    if alias:
        col = f"{alias}.{col}"
    return f"{col} NOT IN ({excluded_gramm_bon_article_ids_sql()})"


def closed_market_filter_condition(alias: str | None = None) -> str:
    """Remove transactions belonging to markets marked as closed."""
    col = ident(MARKET_ID_COL)
    if alias:
        col = f"{alias}.{col}"
    ids = closed_market_ids()
    if not ids:
        return "TRUE"
    ids_sql = ", ".join(str(market_id) for market_id in ids)
    return f"COALESCE(TRY_CAST({col} AS BIGINT) NOT IN ({ids_sql}), TRUE)"


def wgr_filter_condition(alias: str | None = None) -> str:
    """Keep transactions assigned to one of the selected WGR groups."""
    col = ident(WGR_ID_COL)
    if alias:
        col = f"{alias}.{col}"
    allowed = ", ".join(str(wgr_id) for wgr_id in sorted(ALLOWED_WGR_IDS))
    return f"{col} IN ({allowed})"


def transaction_date_filter_condition(alias: str | None = None) -> str:
    col = ident(DATE_COL)
    if alias:
        col = f"{alias}.{col}"
    return (
        f"TRY_CAST({col} AS DATE) BETWEEN "
        f"DATE {sql_literal(MIN_TRANSACTION_DATE)} AND "
        f"DATE {sql_literal(MAX_TRANSACTION_DATE)}"
    )


def ums_menge_filter_condition(alias: str | None = None) -> str:
    col = ident(UMS_MENGE_COL)
    if alias:
        col = f"{alias}.{col}"
    return f"{col} > {MIN_UMS_MENGE}"


def artikel_bez_filter_condition(alias: str | None = None) -> str:
    col = ident(ARTIKEL_BEZ_COL)
    if alias:
        col = f"{alias}.{col}"
    normalized_col = f"LOWER(TRIM(COALESCE(CAST({col} AS VARCHAR), '')))"
    excluded_values = ", ".join(
        sql_literal(value.lower()) for value in sorted(EXCLUDED_ARTIKEL_BEZ_VALUES)
    )
    return f"{normalized_col} NOT IN ({excluded_values})"


def gewicht_flag_expression_sql(alias: str | None = None) -> str:
    col = ident(ARTIKEL_INHALT_COL)
    if alias:
        col = f"{alias}.{col}"
    content = f"LOWER(COALESCE(CAST({col} AS VARCHAR), ''))"
    return (
        f"CASE WHEN {content} LIKE {sql_literal(WEIGHT_CONTENT_LIKE)} "
        "THEN 1 ELSE 0 END"
    )


def weight_filter_condition(alias: str | None = None) -> str:
    return f"({gewicht_flag_expression_sql(alias)}) = 1"


def active_rule_flags(
    *, include_fcm: bool | None = None
) -> tuple[bool, bool, bool, bool, bool]:
    fcm_rule = bool(FCM_RULE) if include_fcm is None else bool(FCM_RULE and include_fcm)
    return (
        fcm_rule,
        bool(EXTERNAL_PRODUCT_RULE),
        bool(WEIGHT_RULE),
        bool(GRAMM_BON_RULE),
        bool(WGR_RULE),
    )


def transaction_filter_condition(
    alias: str | None = None,
    *,
    include_fcm: bool | None = None,
    columns: Collection[str] | None = None,
) -> str:
    (
        fcm_rule,
        external_product_rule,
        weight_rule,
        gramm_bon_rule,
        wgr_rule,
    ) = active_rule_flags(include_fcm=include_fcm)
    conditions = [f"({transaction_date_filter_condition(alias)})"]
    conditions.append(f"({ums_menge_filter_condition(alias)})")
    conditions.append(f"({artikel_bez_filter_condition(alias)})")
    conditions.append(f"({closed_market_filter_condition(alias)})")
    if fcm_rule:
        conditions.append(f"({fcm_filter_condition(alias, columns=columns)})")
    if external_product_rule:
        conditions.append(
            f"({fcm_or_pseudo_filter_condition(alias, columns=columns)})"
        )
    if weight_rule:
        conditions.append(f"({weight_filter_condition(alias)})")
    if wgr_rule:
        conditions.append(f"({wgr_filter_condition(alias)})")
    if gramm_bon_rule:
        conditions.append(f"({gramm_bon_filter_condition(alias)})")
    return " AND ".join(conditions)


def duplicate_keys_sql(alias: str | None = None) -> str:
    prefix = f"{alias}." if alias else ""
    return ", ".join(f"{prefix}{ident(col)}" for col in DUPLICATE_KEY_COLS)


